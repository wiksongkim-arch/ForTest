def set_language(language: str) -> str:
    """切换当前进程语言；持久化由桌面偏好组件负责。"""

    global _CURRENT_LANGUAGE
    valid = {item.code for item in LANGUAGES}
    _CURRENT_LANGUAGE = language if language in valid else "zh_CN"
    return _CURRENT_LANGUAGE


def current_language() -> str:
    return _CURRENT_LANGUAGE


def tr(source: str, **values: Any) -> str:
    """翻译一个界面语义键，并安全替换命名占位符。"""

    translated = _CATALOGS.get(_CURRENT_LANGUAGE, {}).get(source)
    if translated is None:
        translated = source.translate(_TRADITIONAL_TABLE) if _CURRENT_LANGUAGE == "zh_TW" else source
    try:
        return translated.format(**values)
    except (KeyError, ValueError):
        return translated


_TEMPLATE_FIELD = re.compile(r"\{([A-Za-z_][A-Za-z0-9_]*)\}")


@lru_cache(maxsize=None)
def _compiled_template(
    template: str,
) -> tuple[re.Pattern[str], tuple[str, ...]] | None:
    """每个动态文案模板只编译一次，避免首屏翻译反复创建正则表达式。"""

    fields = tuple(_TEMPLATE_FIELD.findall(template))
    if not fields or len(fields) != len(set(fields)):
        return None
    pattern = re.escape(template)
    for field in fields:
        pattern = pattern.replace(r"\{" + field + r"\}", rf"(?P<{field}>.*?)", 1)
    return re.compile(pattern, flags=re.DOTALL), fields


def _match_template(text: str, template: str) -> dict[str, str] | None:
    """从已格式化文案中恢复命名参数，支持动态状态即时切换语言。"""

    compiled = _compiled_template(template)
    if compiled is None:
        return None
    match = compiled[0].fullmatch(text)
    return match.groupdict() if match is not None else None


@lru_cache(maxsize=1)
def _translation_indexes() -> tuple[
    dict[str, str],
    tuple[tuple[str, re.Pattern[str]], ...],
]:
    """预建静态反向索引和少量动态模板索引，保证控件数量线性扩展。"""

    exact_sources: dict[str, str] = {}
    # 保留旧实现先检查显式翻译的优先级，避免同文案键值冲突时行为变化。
    for catalog in _CATALOGS.values():
        for source, translated in catalog.items():
            exact_sources.setdefault(translated, source)
    sources = tuple(dict.fromkeys((*_ZH_TW, *_EN_US)))
    dynamic_templates: list[tuple[str, re.Pattern[str]]] = []
    seen_dynamic: set[tuple[str, str]] = set()
    for source in sources:
        candidates = [source]
        # 繁中缺少显式条目时使用字形转换；这里也必须能反向识别，才能连续切换语言。
        candidates.append(source.translate(_TRADITIONAL_TABLE))
        candidates.extend(
            catalog[source]
            for catalog in _CATALOGS.values()
            if source in catalog
        )
        for template in candidates:
            exact_sources.setdefault(template, source)
            compiled = _compiled_template(template)
            dynamic_key = (source, template)
            if compiled is not None and dynamic_key not in seen_dynamic:
                seen_dynamic.add(dynamic_key)
                dynamic_templates.append((source, compiled[0]))
    return exact_sources, tuple(dynamic_templates)


@lru_cache(maxsize=2048)
def _cached_source_text_and_values(
    text: str,
) -> tuple[str, tuple[tuple[str, str], ...]]:
    """缓存已识别控件文案；同一文案在二次翻译时可直接复用结果。"""

    exact_sources, dynamic_templates = _translation_indexes()
    source = exact_sources.get(text)
    if source is not None:
        return source, ()
    for source, pattern in dynamic_templates:
        match = pattern.fullmatch(text)
        if match is not None:
            return source, tuple(match.groupdict().items())
    return text, ()


def _source_text_and_values(text: str) -> tuple[str, dict[str, str]]:
    """把任意已翻译文本还原为目录键及动态参数。"""

    source, values = _cached_source_text_and_values(text)
    return source, dict(values)


def _source_text(text: str) -> str:
    """兼容静态控件的目录键还原。"""

    return _source_text_and_values(text)[0]


def translate_widget_tree(root: Any) -> None:
    """即时翻译现有 Qt 控件；动态业务内容不会被误改。"""

    try:
        from PySide6.QtCore import Qt
        from PySide6.QtWidgets import (
            QAbstractButton,
            QComboBox,
            QGroupBox,
            QLabel,
            QLineEdit,
            QPlainTextEdit,
            QTabWidget,
            QTableWidget,
            QWidget,
        )
    except ImportError:
        return
    if not isinstance(root, QWidget):
        return
    widgets = [root, *root.findChildren(QWidget)]
    for widget in widgets:
        if isinstance(widget, (QLabel, QAbstractButton, QGroupBox)):
            text_value = widget.text() if hasattr(widget, "text") else widget.title()
            # 每次都从当前文本重新识别键，避免状态标签更新后沿用旧键。
            source, values = _source_text_and_values(str(text_value))
            stored_source = widget.property("i18n_source_text")
            if source not in _ZH_TW and source not in _EN_US and stored_source:
                source = str(stored_source)
            if source in _ZH_TW or source in _EN_US:
                widget.setProperty("i18n_source_text", source)
                if isinstance(widget, QGroupBox):
                    widget.setTitle(tr(source, **values))
                else:
                    widget.setText(tr(source, **values))
        if isinstance(widget, (QLineEdit, QPlainTextEdit)):
            placeholder = widget.placeholderText()
            source = widget.property("i18n_placeholder") or _source_text(placeholder)
            if source in _ZH_TW or source in _EN_US:
                widget.setProperty("i18n_placeholder", source)
                widget.setPlaceholderText(tr(source))
        if isinstance(widget, QTabWidget):
            for index in range(widget.count()):
                property_name = f"i18n_tab_source_{index}"
                source = widget.property(property_name) or _source_text(
                    widget.tabText(index)
                )
                if source in _ZH_TW or source in _EN_US:
                    widget.setProperty(property_name, source)
                    widget.setTabText(index, tr(source))
        if isinstance(widget, QTableWidget):
            for index in range(widget.columnCount()):
                item = widget.horizontalHeaderItem(index)
                if item is None:
                    continue
                source = item.data(Qt.UserRole + 99) or _source_text(item.text())
                if source in _ZH_TW or source in _EN_US:
                    item.setData(Qt.UserRole + 99, source)
                    item.setText(tr(source))
        if isinstance(widget, QComboBox):
            for index in range(widget.count()):
                source = widget.itemData(index, Qt.UserRole + 99) or _source_text(
                    widget.itemText(index)
                )
                if source in _ZH_TW or source in _EN_US:
                    widget.setItemData(index, source, Qt.UserRole + 99)
                    widget.setItemText(index, tr(source))
